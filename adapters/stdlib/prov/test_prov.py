"""prov: the record as PROV-JSON: bites that used passages, suggestions
generated by passing proposals, a seal tying the person to the answer and the
passages it came from; a forged seal or a changed proposal file left out and
said; the same bytes twice; written once and never over a file; a bad
command line or a broken record refused."""

from __future__ import annotations

import hashlib
import importlib.util
import json
import os
import stat
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE / "prov.py"
KERNEL = HERE.parents[2] / "kernel.py"
NOW = ["--now", "2026-10-23T00:00:00Z"]
spec = importlib.util.spec_from_file_location("kernel_for_prov", KERNEL)
kernel = importlib.util.module_from_spec(spec)
spec.loader.exec_module(kernel)


def run(*argv: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, *argv], capture_output=True, text=True)


def subject(row: dict) -> str:
    canon = json.dumps({k: row[k] for k in ("path", "data", "cites", "claim")},
                       sort_keys=True, separators=(",", ":"), ensure_ascii=False)  # fmt: skip
    return "proposal:" + hashlib.sha256(canon.encode()).hexdigest()


def box(tmp_path: Path, seal: bool = True) -> tuple[Path, str, str]:
    """(box, the suggestion's subject, the cited passage's id)."""
    pile = tmp_path / "pile"
    pile.mkdir()
    (pile / "garden.md").write_text("Tomatoes want six hours of sun.\n")
    b = tmp_path / "box"
    run(
        str(KERNEL),
        "init",
        "--box",
        str(b),
        "--pile",
        str(pile),
        "--key",
        str(tmp_path / "k"),
        *NOW,
    )
    got = json.loads(
        run(
            str(KERNEL), "bite", "--box", str(b), *NOW, "how much sun do tomatoes want"
        ).stdout
    )
    pid = got["served"][0]["id"]
    row = {
        "path": "sun.md",
        "data": "Six hours.",
        "cites": [pid],
        "claim": "the garden notes",
    }
    (tmp_path / "r.jsonl").write_text(json.dumps(row) + "\n")
    run(
        str(KERNEL),
        "propose",
        "--box",
        str(b),
        "--file",
        str(tmp_path / "r.jsonl"),
        *NOW,
    )
    if seal:
        run(str(KERNEL), "seal", "--box", str(b), subject(row), *NOW)
    return b, subject(row), pid


def export(b: Path, to: Path) -> tuple[subprocess.CompletedProcess, dict]:
    got = run(str(SCRIPT), "--box", str(b), "--to", str(to))
    return got, json.loads(to.read_text()) if to.exists() else {}


def links(doc: dict, kind: str) -> list[dict]:
    return list(doc.get(kind, {}).values())


def test_a_sealed_answer_is_traced_to_the_passage_the_suggestion_and_the_person(
    tmp_path,
):
    b, subj, pid = box(tmp_path)
    got, doc = export(b, tmp_path / "p.json")
    assert got.returncode == 0, got.stderr
    h = subj[9:]
    assert {"prov:activity": "w:row/1", "prov:entity": f"w:passage/{pid}"} in links(
        doc, "used"
    )
    assert {"prov:activity": "w:row/3", "prov:entity": f"w:suggestion/{h}"} in links(
        doc, "used"
    )
    assert {"prov:entity": f"w:suggestion/{h}", "prov:activity": "w:row/2"} in links(
        doc, "wasGeneratedBy"
    )
    assert {"prov:entity": f"w:answer/{h}", "prov:activity": "w:row/3"} in links(
        doc, "wasGeneratedBy"
    )
    assert {"prov:informed": "w:row/2", "prov:informant": "w:row/1"} in links(
        doc, "wasInformedBy"
    )
    derived = links(doc, "wasDerivedFrom")
    assert {
        "prov:generatedEntity": f"w:answer/{h}",
        "prov:usedEntity": f"w:suggestion/{h}",
    } in derived
    assert {
        "prov:generatedEntity": f"w:answer/{h}",
        "prov:usedEntity": f"w:passage/{pid}",
    } in derived
    assert {"prov:activity": "w:row/3", "prov:agent": "w:person"} in links(
        doc, "wasAssociatedWith"
    )
    assert doc["entity"][f"w:passage/{pid}"]["w:where"] == "garden.md:1"
    assert doc["agent"]["w:person"]["prov:type"] == "prov:Person"
    assert doc["activity"]["w:row/3"]["w:standing"] == "sealed"
    assert "wrote" in got.stdout and "4 activities" in got.stdout


def test_an_unsealed_suggestion_is_an_entity_with_no_answer(tmp_path):
    b, subj, _ = box(tmp_path, seal=False)
    got, doc = export(b, tmp_path / "p.json")
    assert got.returncode == 0
    assert f"w:suggestion/{subj[9:]}" in doc["entity"]
    assert not any(k.startswith("w:answer/") for k in doc["entity"])
    assert "wasDerivedFrom" not in doc


def test_a_decline_used_the_suggestion_and_generated_nothing(tmp_path):
    b, subj, _ = box(tmp_path, seal=False)
    assert run(str(KERNEL), "decline", "--box", str(b), subj, *NOW).returncode == 0
    got, doc = export(b, tmp_path / "p.json")
    assert {
        "prov:activity": "w:row/3",
        "prov:entity": f"w:suggestion/{subj[9:]}",
    } in links(doc, "used")
    assert doc["activity"]["w:row/3"]["prov:type"] == "w:decline"
    assert not any(k.startswith("w:answer/") for k in doc["entity"])


def test_a_forged_seal_is_left_out_and_waits_on_you(tmp_path):
    b, subj, _ = box(tmp_path, seal=False)
    kernel.append(
        b, "2026-10-23T00:00:00Z", "seal", who="human", subject=subj, proof="0" * 64
    )
    got, doc = export(b, tmp_path / "p.json")
    assert got.returncode == 42
    assert "1 seal left out (rows [3])" in got.stderr
    assert not any(k.startswith("w:answer/") for k in doc["entity"])
    assert {
        "prov:activity": "w:row/3",
        "prov:entity": f"w:suggestion/{subj[9:]}",
    } not in links(doc, "used")


def test_a_changed_proposal_file_leaves_the_seal_out(tmp_path):
    b, subj, _ = box(tmp_path)
    f = b / "proposals" / f"{subj[9:]}.json"
    f.write_text(f.read_text().replace("Six hours.", "Eight hours."))
    got, doc = export(b, tmp_path / "p.json")
    assert got.returncode == 42 and "left out" in got.stderr
    assert not any(k.startswith("w:answer/") for k in doc["entity"])


def test_a_question_answered_by_a_seal_names_the_seal_and_serves_nothing(tmp_path):
    b, subj, _ = box(tmp_path)
    run(str(KERNEL), "bite", "--box", str(b), *NOW, "how much sun do tomatoes want")
    _, doc = export(b, tmp_path / "p.json")
    assert doc["activity"]["w:row/4"]["w:answered_by"] == subj


def test_an_add_ons_row_is_an_activity_of_its_own_agent(tmp_path):
    b, _, _ = box(tmp_path, seal=False)
    kernel.append(b, "2026-10-23T00:00:00Z", "gold", who="pile-gold", n_asked=1)
    _, doc = export(b, tmp_path / "p.json")
    assert doc["agent"]["w:pile-gold"]["prov:type"] == "prov:SoftwareAgent"
    assert {"prov:activity": "w:row/3", "prov:agent": "w:pile-gold"} in links(
        doc, "wasAssociatedWith"
    )


def test_the_same_record_gives_the_same_bytes_and_no_words_are_kept(tmp_path):
    b, _, _ = box(tmp_path)
    export(b, tmp_path / "one.json")
    export(b, tmp_path / "two.json")
    assert (tmp_path / "one.json").read_bytes() == (tmp_path / "two.json").read_bytes()
    assert "tomatoes" not in (tmp_path / "one.json").read_text().lower()


def test_the_file_is_written_once_private_and_never_over_a_file(tmp_path):
    b, _, _ = box(tmp_path)
    to = tmp_path / "p.json"
    assert run(str(SCRIPT), "--box", str(b), "--to", str(to)).returncode == 0
    assert stat.S_IMODE(os.stat(to).st_mode) == 0o600
    again = run(str(SCRIPT), "--box", str(b), "--to", str(to))
    assert again.returncode == 2 and "could not write" in again.stderr
    assert (
        run(
            str(SCRIPT), "--box", str(b), "--to", str(tmp_path / "nope" / "p.json")
        ).returncode
        == 2
    )


def test_a_record_that_does_not_verify_is_refused_and_nothing_written(tmp_path):
    b, _, _ = box(tmp_path)
    rec = b / "record.jsonl"
    rec.write_text(rec.read_text().replace("garden.md", "garden.mx", 1))
    to = tmp_path / "p.json"
    got = run(str(SCRIPT), "--box", str(b), "--to", str(to))
    assert got.returncode == 2 and not to.exists()


def test_a_bad_command_line_says_how_to_run_it(tmp_path):
    for argv in ([], ["--box"], ["--box", str(tmp_path)], ["--to", str(tmp_path / "x")],
                 ["--box", str(tmp_path), "--to", str(tmp_path / "x"), "stray"]):  # fmt: skip
        got = run(str(SCRIPT), *argv)
        assert got.returncode == 2 and "prov.py" in got.stderr
    assert (
        run(str(SCRIPT), "--box", str(tmp_path), "--to", str(tmp_path / "x")).returncode
        == 2
    )


def test_a_refused_proposal_is_an_activity_that_made_no_suggestion(tmp_path):
    b, _, _ = box(tmp_path, seal=False)
    (tmp_path / "bad.jsonl").write_text('{"path": "x"}\n')
    run(
        str(KERNEL),
        "propose",
        "--box",
        str(b),
        "--file",
        str(tmp_path / "bad.jsonl"),
        *NOW,
    )
    got, doc = export(b, tmp_path / "p.json")
    assert got.returncode == 0, got.stderr
    assert doc["activity"]["w:row/3"]["prov:type"] == "w:proposal"
    assert len([k for k in doc["entity"] if k.startswith("w:suggestion/")]) == 1
