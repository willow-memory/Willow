"""prov.py: the record as W3C PROV (PROV-JSON): what came from what, by which
step, sealed by whom. Python 3.9+.

    python adapters/stdlib/prov/prov.py --box DIR --to FILE

Every row of the record is an activity; the people and add-ons that wrote
rows are agents; the passages the files served and the suggestions made from
them are entities. The links PROV has words for are made from what the
record says:

- a `bite` used the passages it served (`used`), and was associated with its
  writer (`wasAssociatedWith`);
- a passing `proposal` generated a suggestion (`wasGeneratedBy`), was informed
  by the bite it was made under (`wasInformedBy`), and the suggestion was
  derived from the passages it cites (`wasDerivedFrom`);
- a `seal` used the suggestion and was associated with the person; the
  sealed answer was generated by it and derived from the suggestion. A `decline`
  used the suggestion the same way, and generated nothing.

A seal is exported only while its proof holds under the person's key (the
kernel's `sealed`, so the key is read there and nowhere here), and its answer
only while the suggestion's file still holds the bytes sealed. A seal that
fails either is left out of the links and said on standard error. The record
keeps no question's words, so neither does the file: a question is its
fingerprint, a passage is its id and where it was.

FILE is written once, readable only by you, never over a file that exists,
the same bytes for the same record. Exit codes, the kernel's: 0 written;
42 written, but a seal was left out and waits on you; 2 refused (including a
record that doesn't verify).
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

STDLIB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(STDLIB.parents[1]))
import kernel  # noqa: E402

PREFIX = {"w": "urn:willow:", "prov": "http://www.w3.org/ns/prov#"}


def build(box: Path, rows: list[dict]) -> tuple[dict, list[int]]:
    """(the PROV-JSON document, the rows of seals left out)."""
    doc: dict[str, dict] = {
        k: {} for k in ("entity", "activity", "agent", "used", "wasGeneratedBy",
                        "wasAssociatedWith", "wasInformedBy", "wasDerivedFrom")
    }  # fmt: skip
    good, no = kernel.sealed(box, rows), kernel.declined(box, rows)
    left: list[int] = []
    counts: dict[str, int] = {}

    def link(kind: str, **ends: str) -> None:
        counts[kind] = counts.get(kind, 0) + 1
        doc[kind][f"_:{kind}{counts[kind]}"] = ends

    def passage(p: dict) -> str:
        ident = f"w:passage/{p['id']}"
        doc["entity"].setdefault(
            ident, {"prov:type": "w:passage", "w:where": p["where"]}
        )
        return ident

    def agent(who: str) -> str:
        ident = "w:person" if who == "human" else f"w:{who}"
        doc["agent"].setdefault(
            ident,
            {
                "prov:type": "prov:Person" if who == "human" else "prov:SoftwareAgent",
                "prov:label": who,
            },
        )
        return ident

    served_by: dict[int, list[str]] = {}
    for r in rows:
        act = f"w:row/{r['n']}"
        doc["activity"][act] = {
            "prov:type": f"w:{r['kind']}",
            "prov:startTime": r["ts"],
            "w:hash": r["hash"],
            "w:standing": r["standing"],
        }
        link(
            "wasAssociatedWith", **{"prov:activity": act, "prov:agent": agent(r["who"])}
        )
        if r["kind"] == "bite":
            if r.get("bite_key"):
                doc["activity"][act]["w:bite_key"] = r["bite_key"]
            if r.get("answered_by"):
                doc["activity"][act]["w:answered_by"] = r["answered_by"]
            served_by[r["n"]] = []
            for p in r.get("served", []):
                served_by[r["n"]].append(passage(p))
                link("used", **{"prov:activity": act, "prov:entity": passage(p)})
        elif r["kind"] == "proposal" and r.get("verdict") == "pass":
            ent = f"w:suggestion/{r['subject'][9:]}"
            doc["entity"].setdefault(ent, {"prov:type": "w:suggestion"})
            link("wasGeneratedBy", **{"prov:entity": ent, "prov:activity": act})
            bite_row = r.get("bite_row")
            if (
                isinstance(bite_row, int)
                and not isinstance(bite_row, bool)
                and 0 <= bite_row < len(rows)
            ):
                link(
                    "wasInformedBy",
                    **{"prov:informed": act, "prov:informant": f"w:row/{bite_row}"},
                )
        elif r["kind"] in ("seal", "decline"):
            subj = r.get("subject", "")
            ent = f"w:suggestion/{subj[9:]}"
            if r["kind"] == "seal" and subj not in good:
                left.append(r["n"])
                continue
            if r["kind"] == "decline" and subj not in no:
                continue
            doc["entity"].setdefault(ent, {"prov:type": "w:suggestion"})
            link("used", **{"prov:activity": act, "prov:entity": ent})
            if r["kind"] != "seal":
                continue
            prop, _, why = kernel.standing(box, rows, subj, r)
            if why is not None:
                left.append(r["n"])
                continue
            ans = f"w:answer/{subj[9:]}"
            doc["entity"][ans] = {
                "prov:type": "w:answer",
                "w:path": prop["path"],
                "w:claim": prop["claim"],
            }
            link("wasGeneratedBy", **{"prov:entity": ans, "prov:activity": act})
            link(
                "wasDerivedFrom",
                **{"prov:generatedEntity": ans, "prov:usedEntity": ent},
            )
            for cite in prop["cites"]:
                found = next(
                    (p for r2 in rows for p in r2.get("served", []) if p["id"] == cite),
                    None,
                )
                if found:
                    link(
                        "wasDerivedFrom",
                        **{
                            "prov:generatedEntity": ans,
                            "prov:usedEntity": passage(found),
                        },
                    )
    return {"prefix": PREFIX, **{k: v for k, v in doc.items() if v}}, left


def main(argv: list[str]) -> int:
    opts, args, it = {}, [], iter(argv)
    for a in it:
        if a in ("--box", "--to"):
            opts[a] = next(it, "")
        else:
            args.append(a)
    if not opts.get("--box") or not opts.get("--to") or args:
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        return kernel.REFUSED
    box, to = Path(opts["--box"]), Path(opts["--to"])
    if not (box / "kernel.json").exists():
        print("refused: not a kernel box; init first", file=sys.stderr)
        return kernel.REFUSED
    rows, breaks = kernel.read(box / "record.jsonl")
    if breaks:
        print("refused:", *breaks, sep="\n  ", file=sys.stderr)
        return kernel.REFUSED
    doc, left = build(box, rows)
    try:
        fd = os.open(to, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except OSError as e:
        print(f"refused: could not write {to}: {type(e).__name__}", file=sys.stderr)
        return kernel.REFUSED
    with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n")
    print(f"wrote {to}: {len(rows)} activities, {len(doc.get('entity', {}))} entities, "
          f"{len(doc.get('agent', {}))} agents")  # fmt: skip
    if left:
        print(f"{len(left)} seal{'s' if len(left) != 1 else ''} left out (rows {left}): its proof, or "
              "its proposal file, doesn't hold; python kernel.py verify says which", file=sys.stderr)  # fmt: skip
        return kernel.ESCALATE
    return kernel.ALIVE


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
